import { useState } from "react";
import { Flex } from "@chakra-ui/react";
import { IconType } from "react-icons";
import { GiRobotAntennas, GiHouseKeys } from "react-icons/gi";

import PhraseRow from "./PhraseRow";
import { useMnemonic } from "../clients/mnemonic";
import MnemonicErrorAlert from "./MnemonicErrorAlert";
import ConfigPanel, { type PassphraseConfig } from "./ConfigPanel";
import GeneratorActions from "./GeneratorActions";
import { generatePassphrase } from "../lib/passphrase";
import { DEFAULT_WORDS } from "../../shared/passphrase";
import { DEFAULT_AI_MODE } from "../../shared/api";

const PassphraseGenerator = () => {
  const [currentPassphrase, setCurrentPassphrase] = useState<string | null>(
    null,
  );
  const [isConfigOpen, setIsConfigOpen] = useState(false);
  const [passphraseConfig, setPassphraseConfig] = useState<PassphraseConfig>({
    wordCount: DEFAULT_WORDS,
    mode: DEFAULT_AI_MODE,
  });

  const toggleConfig = () => {
    setIsConfigOpen((openState) => !openState);
  };

  const { mnemonic, error, isLoading, generate } = useMnemonic();

  const handleNewPassphrase = () => {
    const nextPassphrase = generatePassphrase(passphraseConfig.wordCount);
    setCurrentPassphrase(nextPassphrase);
    void generate(nextPassphrase, passphraseConfig.mode);
  };

  const handleRegenerateMnemonic = () => {
    if (currentPassphrase) {
      void generate(currentPassphrase, passphraseConfig.mode);
    }
  };

  const updateConfig = (patch: Partial<PassphraseConfig>) => {
    setPassphraseConfig((priorConfig) => ({ ...priorConfig, ...patch }));
  };

  return (
    <Flex
      as="main"
      direction="column"
      justify="center"
      minWidth={[100, 200, 400, 600]}
    >
      {currentPassphrase && (
        <PhraseRow
          icon={GiHouseKeys as IconType}
          iconLabel="A set of keys symbolizing a phrase to use a password"
          phrase={currentPassphrase}
          phraseLabel={`A set of random words: "${currentPassphrase}"`}
          copyLabel="Copy passphrase"
        />
      )}
      {error && <MnemonicErrorAlert error={error} />}
      {!error && mnemonic && (
        <PhraseRow
          icon={GiRobotAntennas as IconType}
          iconLabel="A robot indicating the mnemonic is generated by AI"
          phrase={mnemonic}
          phraseLabel={`An AI generated mnemonic for the random words "${currentPassphrase}": ${mnemonic}`}
          copyLabel="Copy mnemonic"
          monospace
        />
      )}
      <ConfigPanel
        isOpen={isConfigOpen}
        config={passphraseConfig}
        onChange={updateConfig}
      />
      <GeneratorActions
        hasPassphrase={currentPassphrase !== null}
        isLoading={isLoading}
        onNewPassphrase={handleNewPassphrase}
        onRegenerate={handleRegenerateMnemonic}
        onToggleConfig={toggleConfig}
      />
    </Flex>
  );
};

export default PassphraseGenerator;
